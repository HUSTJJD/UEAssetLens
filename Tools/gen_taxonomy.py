#!/usr/bin/env python3
"""Render the declarative UAL rule YAML into three C++ headers.

    python Tools/gen_taxonomy.py           # regenerate all headers
    python Tools/gen_taxonomy.py --check   # drift gate (non-zero if any is stale)

Outputs (all derived from YAML, which is the single source of truth):

  * Source/UEAssetLensEditor/Public/UALTaxonomyRules.h   - family match rules
  * Source/UEAssetLensEditor/Public/UALFeatureProfiles.h  - profile fragments,
    capability rules and naming prefixes used by the two feature extractors
  * Source/UEAssetLensEditor/Public/UALDomainProfiles.h  - M2 domain profiles
    and typed field rules from Config/UAL/fields/default.yaml

Uses the standard library plus PyYAML (declared in requirements-docs.txt, which
the docs workflow installs). Never edit the generated headers by hand: adding a
taxonomy family also needs a `profiles` YAML entry, and adding a fields family
needs a `domain_profiles` entry. The generator rejects incomplete coverage so no
extractor can silently fall back to a hard-coded table.
"""
from __future__ import annotations

import argparse
import math
import re
import sys
import yaml
from pathlib import Path
from typing import Any, Callable

ROOT = Path(__file__).resolve().parents[1]
RULES_RELATIVE = Path("Server") / "ual_common" / "taxonomy.yaml"
FIELDS_RELATIVE = Path("Config") / "UAL" / "fields" / "default.yaml"
TAXONOMY_HEADER_RELATIVE = (
    Path("Source") / "UEAssetLensEditor" / "Public" / "UALTaxonomyRules.h"
)
FEATURE_HEADER_RELATIVE = (
    Path("Source") / "UEAssetLensEditor" / "Public" / "UALFeatureProfiles.h"
)
DOMAIN_HEADER_RELATIVE = (
    Path("Source") / "UEAssetLensEditor" / "Public" / "UALDomainProfiles.h"
)

# Legacy absolute constants, kept for callers importing this module. Path
# resolution inside main() re-reads ROOT so a test can point it at a temp tree.
RULES_PATH = ROOT / RULES_RELATIVE
HEADER_PATH = ROOT / TAXONOMY_HEADER_RELATIVE

BANNER = (
    "// AUTO-GENERATED by Tools/gen_taxonomy.py from Server/ual_common/taxonomy.yaml.\n"
    "// DO NOT EDIT. Edit the YAML and re-run the generator; --check enforces this.\n"
)
DOMAIN_BANNER = (
    "#pragma once\n"
    "// AUTO-GENERATED by Tools/gen_taxonomy.py from Server/ual_common/taxonomy.yaml\n"
    "// and Config/UAL/fields/default.yaml. DO NOT EDIT; --check enforces this.\n"
)

VALUE_TYPES = ("string", "integer", "number", "boolean", "yaml")
DOMAIN_PROFILE_KEYS = {
    "family", "taxonomy_family", "key_prefix", "tag_fragments", "priority",
}
_UNSAFE_TEXT_RE = re.compile(
    r"[A-Za-z]:[\\/]|/Users/|/home/|\b20\d{2}-\d{2}-\d{2}\b"
    r"|\b[0-9a-fA-F]{8}-(?:[0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}\b"
    r"|TODO\(human\)",
    re.IGNORECASE,
)


def _cpp_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'TEXT("{escaped}")'


def _assert_clean_text(value: str, label: str) -> None:
    """Reject volatile data that would make a generated header dirty."""
    if _UNSAFE_TEXT_RE.search(value):
        raise ValueError(f"{label}: local path, timestamp, random ID or TODO marker")
    if any(0x7F <= ord(character) <= 0x9F for character in value):
        raise ValueError(f"{label}: C1 control character")


def _default_text(spec: dict[str, Any]) -> str:
    """Canonical scalar text, or an `items` mapping for a structured default."""
    value_type = spec["type"]
    default = spec["default"]
    if value_type == "string":
        if not isinstance(default, str):
            raise ValueError("fields.yaml: string defaults must be strings")
        text = default
    elif value_type == "boolean":
        if not isinstance(default, bool):
            raise ValueError("fields.yaml: boolean defaults must be booleans")
        text = "true" if default else "false"
    elif value_type == "integer":
        if isinstance(default, bool) or not isinstance(default, int):
            raise ValueError("fields.yaml: integer defaults must be integers")
        text = str(default)
    elif value_type == "number":
        if isinstance(default, bool) or not isinstance(default, (int, float)):
            raise ValueError("fields.yaml: number defaults must be finite numbers")
        number = float(default)
        if not math.isfinite(number):
            raise ValueError("fields.yaml: number defaults must be finite numbers")
        text = f"{number:.4f}"
    else:
        if not isinstance(default, (list, dict)):
            raise ValueError("fields.yaml: yaml defaults must be lists or mappings")
        text = yaml.safe_dump(
            {"items": default},
            default_flow_style=True,
            sort_keys=True,
            allow_unicode=True,
            width=1000,
        ).strip()
    _assert_clean_text(text, "fields.yaml default")
    return text


def validate(data: dict[str, Any], fields: dict[str, Any] | None = None) -> None:
    """Reject a rule table that would silently change extractor behavior."""
    families = data.get("families")
    if not isinstance(families, list) or not families:
        raise ValueError("taxonomy.yaml: 'families' must be a non-empty list")
    family_names: list[str] = []
    for entry in families:
        if not isinstance(entry, dict) or not isinstance(entry.get("name"), str):
            raise ValueError("taxonomy.yaml: every family needs a string name")
        match = entry.get("match")
        if not isinstance(match, list) or not match or not all(
            isinstance(pattern, str) and pattern for pattern in match
        ):
            raise ValueError(f"taxonomy.yaml: family {entry['name']!r} needs match strings")
        family_names.append(entry["name"])
    if len(set(family_names)) != len(family_names):
        raise ValueError("taxonomy.yaml: duplicate family names")

    profiles = data.get("profiles")
    if not isinstance(profiles, dict) or not isinstance(profiles.get("default"), str):
        raise ValueError("taxonomy.yaml: 'profiles.default' must be a fragment string")
    rules = profiles.get("rules")
    if not isinstance(rules, list) or not rules:
        raise ValueError("taxonomy.yaml: 'profiles.rules' must be a non-empty list")
    profile_families: list[str] = []
    for rule in rules:
        if not isinstance(rule, dict) or not isinstance(rule.get("family"), str):
            raise ValueError("taxonomy.yaml: every profile needs a string family")
        if not isinstance(rule.get("keys"), str) or not rule["keys"]:
            raise ValueError(f"taxonomy.yaml: profile {rule['family']!r} needs keys")
        profile_families.append(rule["family"])
    if len(set(profile_families)) != len(profile_families):
        raise ValueError("taxonomy.yaml: duplicate profile families")
    missing = [name for name in family_names if name not in profile_families]
    if missing:
        raise ValueError(
            "taxonomy.yaml: families without profile rules: " + ", ".join(missing)
        )
    fallback = data.get("fallback")
    if not isinstance(fallback, str) or fallback not in profile_families:
        raise ValueError("taxonomy.yaml: the fallback family needs a profile rule")
    unknown = [name for name in profile_families if name not in family_names + [fallback]]
    if unknown:
        raise ValueError("taxonomy.yaml: profile families not in taxonomy: " + ", ".join(unknown))

    capabilities = data.get("capability_rules")
    if not isinstance(capabilities, list) or not capabilities:
        raise ValueError("taxonomy.yaml: 'capability_rules' must be a non-empty list")
    capability_names: list[str] = []
    for rule in capabilities:
        if not isinstance(rule, dict) or not isinstance(rule.get("name"), str):
            raise ValueError("taxonomy.yaml: every capability needs a string name")
        if not isinstance(rule.get("tag_fragment"), str) or not rule["tag_fragment"]:
            raise ValueError(f"taxonomy.yaml: capability {rule['name']!r} needs a tag_fragment")
        capability_names.append(rule["name"])
    if len(set(capability_names)) != len(capability_names):
        raise ValueError("taxonomy.yaml: duplicate capability names")

    prefixes = data.get("prefixes")
    if not isinstance(prefixes, list) or not prefixes or not all(
        isinstance(prefix, str) and prefix for prefix in prefixes
    ):
        raise ValueError("taxonomy.yaml: 'prefixes' must be a non-empty string list")
    if len(set(prefixes)) != len(prefixes):
        raise ValueError("taxonomy.yaml: duplicate prefixes")

    if fields is not None:
        validate_domain_profiles(data, fields)


def validate_fields(fields: dict[str, Any]) -> None:
    """Validate the declarative M2 field families consumed by the generator."""
    if not isinstance(fields, dict):
        raise ValueError("fields.yaml: expected a YAML mapping")
    if type(fields.get("version")) is not int or fields["version"] != 1:
        raise ValueError("fields.yaml: version must be 1")
    families = fields.get("families")
    if not isinstance(families, dict) or not families:
        raise ValueError("fields.yaml: 'families' must be a non-empty mapping")
    for name, family in families.items():
        if not isinstance(name, str) or not name or not isinstance(family, dict):
            raise ValueError("fields.yaml: every family needs a string name and mapping")
        applies = family.get("applies_to")
        if not isinstance(applies, list) or not applies or not all(
            isinstance(item, str) and item for item in applies
        ):
            raise ValueError(f"fields.yaml: family {name!r} needs applies_to strings")
        taxonomy_family = family.get("taxonomy_family")
        if not isinstance(taxonomy_family, str) or not taxonomy_family:
            raise ValueError(f"fields.yaml: family {name!r} needs taxonomy_family")
        if type(family.get("priority")) is not int:
            raise ValueError(f"fields.yaml: family {name!r} needs an integer priority")
        specs = family.get("fields")
        if not isinstance(specs, dict) or not specs:
            raise ValueError(f"fields.yaml: family {name!r} needs field specs")
        for field_name, spec in specs.items():
            if not isinstance(field_name, str) or not field_name or "." in field_name:
                raise ValueError(f"fields.yaml: invalid field name in {name!r}")
            if not isinstance(spec, dict):
                raise ValueError(f"fields.yaml: {name}.{field_name} must be a mapping")
            if spec.get("type") not in VALUE_TYPES:
                raise ValueError(f"fields.yaml: {name}.{field_name} has an invalid type")
            source_key = spec.get("key")
            if not isinstance(source_key, str) or not source_key:
                raise ValueError(f"fields.yaml: {name}.{field_name} needs a source key")
            if "default" not in spec:
                raise ValueError(f"fields.yaml: {name}.{field_name} needs a default")
            if "source" in spec and not isinstance(spec["source"], str):
                raise ValueError(f"fields.yaml: {name}.{field_name} has an invalid source")
            for text in (name, taxonomy_family, field_name, source_key):
                _assert_clean_text(text, "fields.yaml value")
            _default_text(spec)


def validate_domain_profiles(data: dict[str, Any], fields: dict[str, Any]) -> None:
    """Validate one M2 domain profile per fields-config family and its rules."""
    validate(data)  # existing taxonomy/profile/capability/prefix rule checks
    validate_fields(fields)
    domain = data.get("domain_profiles")
    if not isinstance(domain, dict) or set(domain) != {"version", "rules"}:
        raise ValueError("taxonomy.yaml: 'domain_profiles' needs only version and rules")
    if type(domain.get("version")) is not int or domain["version"] != 1:
        raise ValueError("taxonomy.yaml: domain_profiles.version must be 1")
    rules = domain.get("rules")
    if not isinstance(rules, list) or not rules:
        raise ValueError("taxonomy.yaml: 'domain_profiles.rules' must be a non-empty list")

    profile_keys = {
        rule["family"]: rule["keys"] for rule in data["profiles"]["rules"]
    }
    field_families = fields["families"]
    seen: list[str] = []
    prefixes: list[str] = []
    for rule in rules:
        if not isinstance(rule, dict) or set(rule) != DOMAIN_PROFILE_KEYS:
            raise ValueError("taxonomy.yaml: each domain profile needs exactly five keys")
        family = rule["family"]
        if not isinstance(family, str) or not family:
            raise ValueError("taxonomy.yaml: domain profile needs a string family")
        if family in seen:
            raise ValueError("taxonomy.yaml: duplicate domain profile families")
        if family not in field_families:
            raise ValueError("taxonomy.yaml: domain profile family not in fields.yaml")
        seen.append(family)
        if not isinstance(rule["taxonomy_family"], str) or not rule["taxonomy_family"]:
            raise ValueError(f"taxonomy.yaml: domain profile {family!r} needs taxonomy_family")
        if rule["taxonomy_family"] not in profile_keys:
            raise ValueError("taxonomy.yaml: taxonomy_family must exist in profiles.rules")
        if rule["taxonomy_family"] != field_families[family]["taxonomy_family"]:
            raise ValueError("taxonomy.yaml: fields/taxonomy family mapping mismatch")
        key_prefix = rule["key_prefix"]
        if (not isinstance(key_prefix, str) or not key_prefix.startswith("domain.")
                or key_prefix == "domain." or "*" in key_prefix):
            raise ValueError(f"taxonomy.yaml: domain profile {family!r} needs a domain.* prefix")
        if key_prefix in prefixes:
            raise ValueError("taxonomy.yaml: duplicate domain key prefixes")
        prefixes.append(key_prefix)
        fragments = rule["tag_fragments"]
        if not isinstance(fragments, str) or not fragments:
            raise ValueError(f"taxonomy.yaml: domain profile {family!r} needs tag_fragments")
        if "*" in fragments or any(not part for part in fragments.split("|")):
            raise ValueError("taxonomy.yaml: tag_fragments cannot contain '*' or empty fragments")
        if fragments != profile_keys[rule["taxonomy_family"]]:
            raise ValueError("taxonomy.yaml: tag_fragments must mirror profiles.rules keys")
        if type(rule["priority"]) is not int:
            raise ValueError(f"taxonomy.yaml: domain profile {family!r} needs an integer priority")
        if rule["priority"] != field_families[family]["priority"]:
            raise ValueError("taxonomy.yaml: domain/fields priority mismatch")
        for text in (family, rule["taxonomy_family"], key_prefix, fragments):
            _assert_clean_text(text, "domain profile value")
    if set(seen) != set(field_families):
        raise ValueError("taxonomy.yaml: domain_profiles must cover every fields family")


def load_rules(path: Path) -> dict[str, Any]:
    """Load and validate the YAML rule table."""
    with path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a YAML mapping")
    validate(data)
    return data


def load_fields(path: Path) -> dict[str, Any]:
    """Load and validate the declarative fields configuration."""
    with path.open("r", encoding="utf-8") as handle:
        fields = yaml.safe_load(handle)
    if not isinstance(fields, dict):
        raise ValueError(f"{path}: expected a YAML mapping")
    validate_fields(fields)
    return fields


def render_taxonomy_rules(data: dict[str, Any]) -> str:
    """Render UALTaxonomyRules.h (byte-compatible with the original generator)."""
    families = data["families"]
    lines = [
        BANNER.rstrip("\n"),
        "#pragma once",
        "",
        '#include "CoreMinimal.h"',
        "",
        "namespace UALTaxonomyRules",
        "{",
        f"\tstatic const TCHAR* const GRoot     = {_cpp_string(data['root'])};",
        f"\tstatic const TCHAR* const GFallback = {_cpp_string(data['fallback'])};",
        "",
        "\tstruct FFamilyRule",
        "\t{",
        "\t\tconst TCHAR* Name;",
        "\t\tconst TCHAR* const* Patterns;",
        "\t\tint32 PatternCount;",
        "\t};",
        "",
    ]
    for index, entry in enumerate(families):
        patterns = ", ".join(_cpp_string(pattern) for pattern in entry["match"])
        lines.append(f"\tstatic const TCHAR* const GPatterns_{index}[] = {{ {patterns} }};")
    lines += ["", "\t// Ordered: first matching family wins, exactly as in the YAML.", "\tstatic const FFamilyRule GRules[] = {"]
    for index, entry in enumerate(families):
        lines.append(
            f"\t\t{{ {_cpp_string(entry['name'])}, GPatterns_{index}, UE_ARRAY_COUNT(GPatterns_{index}) }},"
        )
    lines += [
        "\t};",
        "\tstatic const int32 GRuleCount = UE_ARRAY_COUNT(GRules);",
        "}",
        "",
    ]
    return "\n".join(lines)


def render(data: dict[str, Any]) -> str:
    """Backward-compatible alias for the taxonomy-rules header renderer."""
    return render_taxonomy_rules(data)


def render_feature_profiles(data: dict[str, Any]) -> str:
    """Render UALFeatureProfiles.h from the YAML's non-family rule sections."""
    lines = [
        BANNER.rstrip("\n"),
        "#pragma once",
        "",
        '#include "CoreMinimal.h"',
        "",
        "namespace UALFeatureProfiles",
        "{",
        "\t// '|' separated AssetRegistry Tag-name fragments; matched case-insensitively.",
        "\t// One rule per taxonomy family plus the fallback family, in YAML order.",
        "\tstruct FFeatureProfileRule",
        "\t{",
        "\t\tconst TCHAR* Family;",
        "\t\tconst TCHAR* Keys;",
        "\t};",
        "",
        "\tstatic const FFeatureProfileRule GProfileRuleTable[] = {",
    ]
    for rule in data["profiles"]["rules"]:
        lines.append(
            f"\t\t{{ {_cpp_string(rule['family'])}, {_cpp_string(rule['keys'])} }},"
        )
    lines += [
        "\t};",
        "\tstatic const int32 GProfileRuleTableCount = UE_ARRAY_COUNT(GProfileRuleTable);",
        "",
        "\t// Defensive fallback when a family has no profile rule (see YAML validation).",
        f"\tstatic const TCHAR* const GDefaultProfileKeys = {_cpp_string(data['profiles']['default'])};",
        "",
        "\t// Capability flags come from Tag *names*, in the YAML's deterministic order.",
        "\tstruct FCapabilityRule",
        "\t{",
        "\t\tconst TCHAR* Name;",
        "\t\tconst TCHAR* TagFragment;",
        "\t};",
        "",
        "\tstatic const FCapabilityRule GCapabilityRuleTable[] = {",
    ]
    for rule in data["capability_rules"]:
        lines.append(
            f"\t\t{{ {_cpp_string(rule['name'])}, {_cpp_string(rule['tag_fragment'])} }},"
        )
    lines += [
        "\t};",
        "\tstatic const int32 GCapabilityRuleTableCount = UE_ARRAY_COUNT(GCapabilityRuleTable);",
        "",
        "\t// Common UE naming prefixes; stripped case-sensitively, in YAML order.",
        "\tstatic const TCHAR* const GNamePrefixes[] = {",
    ]
    for prefix in data["prefixes"]:
        lines.append(f"\t\t{_cpp_string(prefix)},")
    lines += [
        "\t};",
        "\tstatic const int32 GNamePrefixCount = UE_ARRAY_COUNT(GNamePrefixes);",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_domain_profiles(
    data: dict[str, Any], fields: dict[str, Any] | None = None
) -> str:
    """Render UALDomainProfiles.h from taxonomy.yaml and fields/default.yaml."""
    if fields is None:
        fields = load_fields(ROOT / FIELDS_RELATIVE)
    validate_domain_profiles(data, fields)

    profile_rules = {
        rule["family"]: rule for rule in data["domain_profiles"]["rules"]
    }
    lines = [
        DOMAIN_BANNER.rstrip("\n"),
        "",
        '#include "CoreMinimal.h"',
        "",
        "namespace UALDomainProfiles",
        "{",
        "\t// One generated profile per fields-config family. AppliesTo is a pipe-joined",
        "\t// list of exact asset classes, or '*' for the common wildcard family.",
        "\tstruct FUALDomainProfileRule",
        "\t{",
        "\t\tconst TCHAR* DomainFamily;",
        "\t\tconst TCHAR* AppliesTo;",
        "\t\tconst TCHAR* KeyPrefix;",
        "\t\tconst TCHAR* TagFragments;",
        "\t\tint32 Priority;",
        "\t};",
        "",
        "\tstatic const FUALDomainProfileRule GDomainProfileRuleTable[] = {",
    ]
    for family, rule in profile_rules.items():
        applies_to = "|".join(str(item) for item in fields["families"][family]["applies_to"])
        values = (
            family, applies_to, rule["key_prefix"], rule["tag_fragments"],
        )
        for value in values:
            _assert_clean_text(value, "generated domain profile")
        lines.append(
            "\t\t{ " + ", ".join(_cpp_string(value) for value in values)
            + f", {int(rule['priority'])} }},"
        )
    lines += [
        "\t};",
        "\tstatic const int32 GDomainProfileRuleTableCount = UE_ARRAY_COUNT(GDomainProfileRuleTable);",
        "",
        "\t// Every declarative field spec, including common fields, in YAML order.",
        "\tstruct FUALDomainFieldRule",
        "\t{",
        "\t\tconst TCHAR* DomainFamily;",
        "\t\tconst TCHAR* FieldName;",
        "\t\tconst TCHAR* ValueType;",
        "\t\tconst TCHAR* SourceKey;",
        "\t\tconst TCHAR* DefaultText;",
        "\t\tint32 Priority;",
        "\t};",
        "",
        "\tstatic const FUALDomainFieldRule GDomainFieldRuleTable[] = {",
    ]
    for family, family_data in fields["families"].items():
        family_priority = int(family_data["priority"])
        for field_name, spec in family_data["fields"].items():
            values = (
                family, field_name, str(spec["type"]), str(spec["key"]),
                _default_text(spec),
            )
            for value in values:
                _assert_clean_text(value, "generated domain field")
            priority = int(spec.get("priority", family_priority))
            lines.append(
                "\t\t{ " + ", ".join(_cpp_string(value) for value in values)
                + f", {priority} }},"
            )
    lines += [
        "\t};",
        "\tstatic const int32 GDomainFieldRuleTableCount = UE_ARRAY_COUNT(GDomainFieldRuleTable);",
        "}",
        "",
    ]
    return "\n".join(lines)


def _render_taxonomy_bundle(
    data: dict[str, Any], fields: dict[str, Any] | None = None
) -> str:
    return render_taxonomy_rules(data)


def _render_feature_bundle(
    data: dict[str, Any], fields: dict[str, Any] | None = None
) -> str:
    return render_feature_profiles(data)


RENDERERS: tuple[tuple[Path, Callable[..., str]], ...] = (
    (TAXONOMY_HEADER_RELATIVE, _render_taxonomy_bundle),
    (FEATURE_HEADER_RELATIVE, _render_feature_bundle),
    (DOMAIN_HEADER_RELATIVE, render_domain_profiles),
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if any generated header is stale"
    )
    args = parser.parse_args()

    data = load_rules(ROOT / RULES_RELATIVE)
    fields = load_fields(ROOT / FIELDS_RELATIVE)
    validate(data, fields)

    for relative, renderer in RENDERERS:
        path = ROOT / relative
        expected = renderer(data, fields)
        if args.check:
            if not path.exists():
                print(f"DRIFT: missing {relative}", file=sys.stderr)
                return 1
            actual = path.read_text(encoding="utf-8")
            if actual != expected:
                print(
                    f"DRIFT: {relative} is stale; "
                    "run `python Tools/gen_taxonomy.py`",
                    file=sys.stderr,
                )
                return 1
            print(f"OK: {relative} matches {RULES_RELATIVE}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
            print(
                f"WROTE: {relative} ({len(data['families'])} families / "
                f"{len(fields['families'])} domain families)"
            )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
