#!/usr/bin/env python3
"""Render Server/ual_common/taxonomy.json into the C++ rule table.

    python Tools/gen_taxonomy.py           # regenerate the header
    python Tools/gen_taxonomy.py --check   # drift gate (non-zero if stale)

Standard library only: CI installs requirements-docs.txt, not the runtime deps.
The JSON file is the single source of truth; never edit the generated header.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES_PATH = ROOT / "Server" / "ual_common" / "taxonomy.json"
HEADER_PATH = ROOT / "Source" / "UEAssetLensEditor" / "Public" / "UALTaxonomyRules.h"

BANNER = (
    "// AUTO-GENERATED by Tools/gen_taxonomy.py from Server/ual_common/taxonomy.json.\n"
    "// DO NOT EDIT. Edit the JSON and re-run the generator; --check enforces this.\n"
)


def _cpp_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'TEXT("{escaped}")'


def render(data: dict) -> str:
    families = data["families"]
    lines = [
        BANNER.rstrip("\n"),
        "#pragma once",
        "",
        '#include "CoreMinimal.h"',
        "",
        "namespace UALTaxonomyRules",
        "{",
        f"\tstatic const TCHAR* const GRoot     = {_cpp_string(data['root'])};",
        f"\tstatic const TCHAR* const GFallback = {_cpp_string(data['fallback'])};",
        "",
        "\tstruct FFamilyRule",
        "\t{",
        "\t\tconst TCHAR* Name;",
        "\t\tconst TCHAR* const* Patterns;",
        "\t\tint32 PatternCount;",
        "\t};",
        "",
    ]
    for index, entry in enumerate(families):
        patterns = ", ".join(_cpp_string(pattern) for pattern in entry["match"])
        lines.append(f"\tstatic const TCHAR* const GPatterns_{index}[] = {{ {patterns} }};")
    lines += ["", "\t// Ordered: first matching family wins, exactly as in the JSON.", "\tstatic const FFamilyRule GRules[] = {"]
    for index, entry in enumerate(families):
        lines.append(
            f"\t\t{{ {_cpp_string(entry['name'])}, GPatterns_{index}, UE_ARRAY_COUNT(GPatterns_{index}) }},"
        )
    lines += [
        "\t};",
        "\tstatic const int32 GRuleCount = UE_ARRAY_COUNT(GRules);",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated header is stale")
    args = parser.parse_args()

    with RULES_PATH.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    expected = render(data)

    if args.check:
        if not HEADER_PATH.exists():
            print(f"DRIFT: missing {HEADER_PATH.relative_to(ROOT)}", file=sys.stderr)
            return 1
        actual = HEADER_PATH.read_text(encoding="utf-8")
        if actual != expected:
            print(
                f"DRIFT: {HEADER_PATH.relative_to(ROOT)} is stale; "
                "run `python Tools/gen_taxonomy.py`",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {HEADER_PATH.relative_to(ROOT)} matches {RULES_PATH.relative_to(ROOT)}")
        return 0

    HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
    HEADER_PATH.write_text(expected, encoding="utf-8", newline="\n")
    print(f"WROTE: {HEADER_PATH.relative_to(ROOT)} ({len(data['families'])} families)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
