def copy_with_banner(source: str) -> str:
    text = (ROOT / source).read_text(encoding="utf-8").rstrip()
    return f"{BANNER}\n\n> 本页内容同步自 `{source}`，请在该源文件修改后运行 `python Tools/gen_docs.py`。\n\n{text}\n"


# --------------------------------------------------------------------------- driver

def build_pages() -> dict[str, str]:
    """Keys are repository-root-relative paths (not docs-dir-relative)."""
    return {
        "docs/reference/schema.md": parse_schema(),
        "docs/reference/mcp-tools.md": parse_mcp_tools(),
        "docs/reference/cli.md": parse_cli(),
        "docs/reference/protocol.md": copy_with_banner("Server/schema/PROTOCOL.md"),
        "docs/agent-guide.md": copy_with_banner("CLAUDE.md"),
        "Server/ual_mcp/tool_schemas.yaml": build_tool_schemas(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate UAL reference docs")
    parser.add_argument("--check", action="store_true", help="Fail if committed pages are stale")
    args = parser.parse_args(argv)

    pages = build_pages()
    if args.check:
        stale: list[str] = []
        for rel, content in pages.items():
            target = ROOT / rel
            if not target.exists():
                stale.append(f"MISSING  {rel}")
            elif target.read_text(encoding="utf-8") != content:
                stale.append(f"STALE    {rel}")
        known = set(pages)
        for existing in sorted(REF.glob("*.md")):
            rel = existing.relative_to(ROOT).as_posix()
            if rel not in known:
                stale.append(f"ORPHAN   {rel}")
        if stale:
            print("Documentation drift detected. Run `python Tools/gen_docs.py` and commit the result:",
                  file=sys.stderr)
            for item in stale:
                print("  " + item, file=sys.stderr)
            return 1
        print(f"Generated docs are up to date ({len(pages)} pages).")
        return 0

    for rel, content in pages.items():
        target = ROOT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        print(f"generated {rel} ({len(content)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
