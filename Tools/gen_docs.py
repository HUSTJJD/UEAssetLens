#!/usr/bin/env python3
"""Generate UAL API reference pages from the source of truth.

This generator uses the standard library plus PyYAML (declared in
requirements-docs.txt, which the docs workflow installs); it does not need the
DuckDB / MCP runtime dependencies.

Sources -> generated pages:
  Server/schema/init.sql, rebuild_fts.sql -> docs/reference/schema.md
  Server/schema/PROTOCOL.md               -> docs/reference/protocol.md
  Server/ual_mcp/tools.py                 -> docs/reference/mcp-tools.md  (TOOL_DEFS + TOON field order)
  Server/ual_cli/ual_cli.py               -> docs/reference/cli.md        (argparse)
  CLAUDE.md                               -> docs/agent-guide.md
  Server/ual_mcp/tools.py                 -> Server/ual_mcp/tool_schemas.yaml
                                             (shared by the C++ in-editor MCP tools)

Usage:
  python Tools/gen_docs.py            regenerate committed pages
  python Tools/gen_docs.py --check    fail (exit 1) if committed pages are stale
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
import yaml
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REF = DOCS / "reference"

BANNER = "<!-- AUTO-GENERATED by Tools/gen_docs.py - DO NOT EDIT BY HAND. -->"

OUTPUTS: dict[str, tuple[str, str]] = {
    "ual_search_assets": (
        "TOON：section `candidates` + `co_occurring_bundle`",
        "`Server/ual_mcp/tools.py`",
    ),
    "ual_inspect_asset": (
        "YAML：完整 AssetSpec（优先读 `assets.yaml_cache`）",
        "`Server/ual_common/yamlspec.py`",
    ),
    "ual_get_cooccurring_bundle": (
        "TOON：section `co_occurring_bundle`",
        "`Server/ual_mcp/tools.py`",
    ),
    "ual_find_similar_assets": (
        "TOON：section `similar_assets`",
        "`Server/ual_mcp/tools.py`",
    ),
}


def _cell(value: Any) -> str:
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join(["---"] * len(headers)) + " |"]
    for row in rows:
        out.append("| " + " | ".join(_cell(c) for c in row) + " |")
    return "\n".join(out)


def _fence(lang: str, body: str) -> str:
    return f"```{lang}\n{body.rstrip()}\n```"


def _const(node: ast.AST) -> Any:
    try:
        return ast.literal_eval(node)
    except Exception:
        return None


def _kw(call: ast.Call, name: str) -> Any:
    for kw in call.keywords:
        if kw.arg == name:
            # argparse uses `type=float`, an ast.Name rather than a literal.
            if isinstance(kw.value, ast.Name):
                return kw.value.id
            if isinstance(kw.value, ast.Attribute):
                return kw.value.attr
            return _const(kw.value)
    return None


# --------------------------------------------------------------------------- schema

def parse_schema() -> str:
    sql_src = (ROOT / "Server/schema/init.sql").read_text(encoding="utf-8")
    rebuild = (ROOT / "Server/schema/rebuild_fts.sql").read_text(encoding="utf-8")
    lines = [
        "# DuckDB 存储参考",
        BANNER,
        "",
        "> 生成来源：`Server/schema/init.sql`、`Server/schema/rebuild_fts.sql`。"
        "字段契约以 `docs/reference/protocol.md` 为准；本页是 DDL 的结构化投影。",
        "",
        "## schema_meta",
        "",
    ]
    meta = re.findall(r"INSERT OR REPLACE INTO schema_meta VALUES \('([^']+)', '([^']+)'\)", sql_src)
    lines += [_table(["key", "value"], [[k, v] for k, v in meta]), ""]

    for match in re.finditer(r"CREATE TABLE IF NOT EXISTS (\w+)\s*\((.*?)\n\);", sql_src, re.S):
        name, body = match.group(1), match.group(2)
        if name == "schema_meta":  # already rendered above from the INSERT values
            continue
        rows: list[list[Any]] = []
        for raw in body.splitlines():
            code, _, comment = raw.strip().partition("--")
            code = code.strip().rstrip(",")
            if not code:
                continue
            parts = code.split(None, 1)
            if len(parts) < 2:
                continue
            col, typ = parts[0].strip(), parts[1].strip()
            if col.upper() in {"PRIMARY", "UNIQUE", "CHECK", "CONSTRAINT", "FOREIGN"}:
                continue
            rows.append([f"`{col}`", f"`{typ}`", comment.strip()])
        lines += [f"## {name}", "", _table(["列", "类型", "说明"], rows), ""]

    view = re.search(r"CREATE OR REPLACE VIEW v_search AS.*?;", sql_src, re.S)
    if view:
        lines += [
            "## v_search 投影视图",
            "",
            "把 `domain_spec` 中的键投影为可过滤列，避免在物理表中新增列。",
            "",
            _fence("sql", view.group(0)),
            "",
        ]

    pragmas = [ln.strip() for ln in sql_src.splitlines()
               if ln.strip().startswith("PRAGMA") and "fts_index" in ln]
    lines += [
        "## FTS 索引（快照语义）",
        "",
        "DuckDB 的 FTS 索引**不会随 INSERT 自动更新**，每次批量灌库后必须重建：",
        "",
        _fence("sql", "\n".join(
            [ln.strip() for ln in rebuild.splitlines()
             if ln.strip().startswith("PRAGMA")])),
        "",
        "初始化时执行的建索引语句：",
        "",
        _fence("sql", "\n".join(pragmas)),
        "",
        "## 查重查询",
        "",
        "`ual-cli lint-duplicates` 使用 `db.duplicate_pairs()` 的余弦自连接，核心表达式为",
        "`array_cosine_similarity(a.fingerprint_vec, b.fingerprint_vec)`，"
        "并要求 DuckDB >= 1.1（已在 2.0.0 实测）。完整 SQL 见 `Server/ual_common/db.py`。",
        "",
    ]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- MCP tools

TOOL_DEFS_SOURCE = "Server/ual_mcp/tools.py"


def load_tool_defs() -> list[dict[str, Any]]:
    """TOOL_DEFS is the single source of truth for all three MCP frontends."""
    src = (ROOT / TOOL_DEFS_SOURCE).read_text(encoding="utf-8")
    for node in ast.parse(src).body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "TOOL_DEFS":
            return ast.literal_eval(node.value)
    raise RuntimeError(f"TOOL_DEFS not found in {TOOL_DEFS_SOURCE}")


def load_registered_tool_names() -> set[str]:
    """Collect the explicit MCP tool names from @sdk.tool(name=...) in server.py.

    The Python function name is an implementation detail; the wire name is what
    the SDK publishes and what TOOL_DEFS.mcp_name must match.
    """
    src = (ROOT / "Server/ual_mcp/server.py").read_text(encoding="utf-8")
    names: set[str] = set()
    for node in ast.walk(ast.parse(src)):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            if not (isinstance(decorator, ast.Call)
                    and isinstance(decorator.func, ast.Attribute)
                    and decorator.func.attr == "tool"):
                continue
            explicit = None
            for kw in decorator.keywords:
                if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                    explicit = kw.value.value
            names.add(explicit if explicit is not None else node.name)
    return names


def build_tool_schemas() -> str:
    """Emit a YAML contract consumed by the C++ in-editor MCP tools."""
    defs = load_tool_defs()
    declared = {tool["mcp_name"] for tool in defs}
    registered = load_registered_tool_names()
    if declared != registered:
        raise RuntimeError(
            "TOOL_DEFS and server.py @sdk.tool() registrations diverged: "
            f"schema-only={sorted(declared - registered)}, "
            f"code-only={sorted(registered - declared)}"
        )
    # The C++ frontend reads tools[].name as the MCP tool name. Publish only
    # the qualified wire name; `name`/`mcp_name` from TOOL_DEFS are internal.
    published = [
        {
            "name": tool["mcp_name"],
            "description": tool["description"],
            "inputSchema": tool["inputSchema"],
        }
        for tool in defs
    ]
    payload = {
        "schema_version": "3.0",
        "source": f"{TOOL_DEFS_SOURCE}::TOOL_DEFS",
        "note": "AUTO-GENERATED by Tools/gen_docs.py - DO NOT EDIT BY HAND.",
        "tools": published,
    }
    return yaml.safe_dump(payload, sort_keys=False, allow_unicode=True,
                          default_flow_style=False)


def parse_mcp_tools() -> str:
    defs = load_tool_defs()
    tools_src = (ROOT / "Server/ual_mcp/tools.py").read_text(encoding="utf-8")
    fields: dict[str, list[str]] = {}
    for node in ast.parse(tools_src).body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            value = _const(node.value)
            for target in targets:
                name = getattr(target, "id", "")
                if name.endswith("_FIELDS") and isinstance(value, (list, tuple)):
                    fields[name] = list(value)

    lines = [
        "# MCP 工具参考", BANNER, "",
        "> 生成来源：`Server/ual_mcp/tools.py`（`TOOL_DEFS` 与 TOON 字段顺序）。"
        "MCP Server 只读连接 `.ual/index.duckdb`。", "",
        f"共 **{len(defs)}** 个工具。批量工具返回 TOON，单资产工具返回 YAML。", "",
    ]
    for tool in defs:
        name = tool["mcp_name"]
        schema = tool.get("inputSchema", {})
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        lines += [f"## `{name}`", "", tool.get("description", ""), ""]
        rows = []
        for prop, spec in props.items():
            default = spec.get("default", "")
            rows.append([
                f"`{prop}`", f"`{spec.get('type', '')}`",
                "是" if prop in required else "否",
                f"`{default}`" if default != "" else "",
                spec.get("description", ""),
            ])
        lines += [_table(["参数", "类型", "必填", "默认值", "说明"], rows), ""]
        output, impl = OUTPUTS.get(tool["name"], ("", ""))
        lines += [f"**返回**：{output}", "", f"**实现**：{impl}", ""]

    lines += ["## TOON section 字段顺序", ""]
    rows = []
    label = {
        "CANDIDATE_FIELDS": "candidates",
        "BUNDLE_FIELDS": "co_occurring_bundle",
        "SIMILAR_FIELDS": "similar_assets",
    }
    for key, values in fields.items():
        rows.append([f"`{label.get(key, key)}`", ", ".join(f"`{v}`" for v in values)])
    lines += [_table(["section", "字段（顺序固定）"], rows), "",
              "字段顺序与转义规则见 `docs/reference/protocol.md`。", ""]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- CLI

def parse_cli() -> str:
    src = (ROOT / "Server/ual_cli/ual_cli.py").read_text(encoding="utf-8")
    tree = ast.parse(src)
    commands: list[tuple[int, str, str]] = []
    arguments: list[tuple[int, list[str], str, Any, str]] = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
            continue
        if node.func.attr == "add_parser" and node.args:
            cmd = _const(node.args[0])
            if isinstance(cmd, str):
                commands.append((node.lineno, cmd, str(_kw(node, "help") or "")))
        elif node.func.attr == "add_argument" and node.args:
            flags = [_const(a) for a in node.args]
            flags = [f for f in flags if isinstance(f, str)]
            if not flags:
                continue
            action = _kw(node, "action")
            default = _kw(node, "default")
            arguments.append((
                node.lineno, flags,
                "flag" if action == "store_true" else str(_kw(node, "type") or ""),
                default,
                str(_kw(node, "help") or ""),
            ))
    commands.sort()
    arguments.sort()

    def owner(line: int) -> str | None:
        found = None
        for lineno, cmd, _ in commands:
            if lineno <= line:
                found = cmd
            else:
                break
        return found

    grouped: dict[str, list[list[Any]]] = {"(global)": []}
    for cmd in commands:
        grouped[cmd[1]] = []
    for lineno, flags, typ, default, help_text in arguments:
        key = owner(lineno) or "(global)"
        grouped.setdefault(key, []).append([
            ", ".join(f"`{f}`" for f in flags), f"`{typ}`" if typ else "",
            f"`{default}`" if default not in (None, "") else "",
            help_text,
        ])

    lines = [
        "# ual-cli 命令参考", BANNER, "",
        "> 生成来源：`Server/ual_cli/ual_cli.py` 的 argparse 定义。"
        "当前仓库未提供 console script，统一用 `python Server/ual_cli/ual_cli.py <command>` 调用。", "",
        "## 全局参数", "",
        _table(["参数", "类型", "默认值", "说明"], grouped["(global)"]), "",
    ]
    for _, cmd, help_text in commands:
        rows = grouped.get(cmd, [])
        lines += [f"## `{cmd}`", "", help_text or "（无附加说明）", ""]
        lines += [_table(["参数", "类型", "默认值", "说明"], rows), ""] if rows else ["（无参数）", ""]
    lines += [
        "## 退出码", "",
        "| 命令 | 通过 | 拦截 | 环境错误 |", "| --- | --- | --- | --- |",
        "| `lint-duplicates` | 0 | 1（发现重复对） | 2（索引缺失） |",
        "| `verify-references` | 0 | 1（发现断裂引用） | 2（索引缺失） |",
        "| `build` / `export-parquet` / `self-test` | 0 | 1 | 2 |", "",
        "门禁细节与 CI 接入见 `ci-gates.md`。", "",
    ]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- copies

def copy_with_banner(source: str) -> str:
    text = (ROOT / source).read_text(encoding="utf-8").rstrip()
    return f"{BANNER}\n\n> 本页内容同步自 `{source}`，请在该源文件修改后运行 `python Tools/gen_docs.py`。\n\n{text}\n"


# --------------------------------------------------------------------------- driver

def build_pages() -> dict[str, str]:
    """Keys are repository-root-relative paths (not docs-dir-relative)."""
    return {
        "docs/reference/schema.md": parse_schema(),
        "docs/reference/mcp-tools.md": parse_mcp_tools(),
        "docs/reference/cli.md": parse_cli(),
        "docs/reference/protocol.md": copy_with_banner("Server/schema/PROTOCOL.md"),
        "docs/agent-guide.md": copy_with_banner("CLAUDE.md"),
        "Server/ual_mcp/tool_schemas.yaml": build_tool_schemas(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate UAL reference docs")
    parser.add_argument("--check", action="store_true", help="Fail if committed pages are stale")
    args = parser.parse_args(argv)

    pages = build_pages()
    if args.check:
        stale: list[str] = []
        for rel, content in pages.items():
            target = ROOT / rel
            if not target.exists():
                stale.append(f"MISSING  {rel}")
            elif target.read_text(encoding="utf-8") != content:
                stale.append(f"STALE    {rel}")
        known = set(pages)
        for existing in sorted(REF.glob("*.md")):
            rel = existing.relative_to(ROOT).as_posix()
            if rel not in known:
                stale.append(f"ORPHAN   {rel}")
        if stale:
            print("Documentation drift detected. Run `python Tools/gen_docs.py` and commit the result:",
                  file=sys.stderr)
            for item in stale:
                print("  " + item, file=sys.stderr)
            return 1
        print(f"Generated docs are up to date ({len(pages)} pages).")
        return 0

    for rel, content in pages.items():
        target = ROOT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        print(f"generated {rel} ({len(content)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
