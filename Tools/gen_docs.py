def _cell(value: Any) -> str:
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join(["---"] * len(headers)) + " |"]
    for row in rows:
        out.append("| " + " | ".join(_cell(c) for c in row) + " |")
    return "\n".join(out)


def _fence(lang: str, body: str) -> str:
    return f"```{lang}\n{body.rstrip()}\n```"


def _const(node: ast.AST) -> Any:
    try:
        return ast.literal_eval(node)
    except Exception:
        return None


def _kw(call: ast.Call, name: str) -> Any:
    for kw in call.keywords:
        if kw.arg == name:
            # argparse uses `type=float`, an ast.Name rather than a literal.
            if isinstance(kw.value, ast.Name):
                return kw.value.id
            if isinstance(kw.value, ast.Attribute):
                return kw.value.attr
            return _const(kw.value)
    return None


