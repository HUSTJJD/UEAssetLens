def parse_cli() -> str:
    src = (ROOT / "Server/ual_cli/ual_cli.py").read_text(encoding="utf-8")
    tree = ast.parse(src)
    commands: list[tuple[int, str, str]] = []
    arguments: list[tuple[int, list[str], str, Any, str]] = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
            continue
        if node.func.attr == "add_parser" and node.args:
            cmd = _const(node.args[0])
            if isinstance(cmd, str):
                commands.append((node.lineno, cmd, str(_kw(node, "help") or "")))
        elif node.func.attr == "add_argument" and node.args:
            flags = [_const(a) for a in node.args]
            flags = [f for f in flags if isinstance(f, str)]
            if not flags:
                continue
            action = _kw(node, "action")
            default = _kw(node, "default")
            arguments.append((
                node.lineno, flags,
                "flag" if action == "store_true" else str(_kw(node, "type") or ""),
                default,
                str(_kw(node, "help") or ""),
            ))
    commands.sort()
    arguments.sort()

    def owner(line: int) -> str | None:
        found = None
        for lineno, cmd, _ in commands:
            if lineno <= line:
                found = cmd
            else:
                break
        return found

    grouped: dict[str, list[list[Any]]] = {"(global)": []}
    for cmd in commands:
        grouped[cmd[1]] = []
    for lineno, flags, typ, default, help_text in arguments:
        key = owner(lineno) or "(global)"
        grouped.setdefault(key, []).append([
            ", ".join(f"`{f}`" for f in flags), f"`{typ}`" if typ else "",
            f"`{default}`" if default not in (None, "") else "",
            help_text,
        ])

    lines = [
        "# ual-cli 命令参考", BANNER, "",
        "> 生成来源：`Server/ual_cli/ual_cli.py` 的 argparse 定义。"
        "当前仓库未提供 console script，统一用 `python Server/ual_cli/ual_cli.py <command>` 调用。", "",
        "## 全局参数", "",
        _table(["参数", "类型", "默认值", "说明"], grouped["(global)"]), "",
    ]
    for _, cmd, help_text in commands:
        rows = grouped.get(cmd, [])
        lines += [f"## `{cmd}`", "", help_text or "（无附加说明）", ""]
        lines += [_table(["参数", "类型", "默认值", "说明"], rows), ""] if rows else ["（无参数）", ""]
    lines += [
        "## 退出码", "",
        "| 命令 | 通过 | 拦截 | 环境错误 |", "| --- | --- | --- | --- |",
        "| `lint-duplicates` | 0 | 1（发现重复对） | 2（索引缺失） |",
        "| `lint-policy` | 0 | 1（enforcing 规则命中或 --strict 命中） | 2（索引缺失） |",
        "| `verify-references` | 0 | 1（发现断裂引用） | 2（索引缺失） |",
        "| `build` / `export-parquet` / `self-test` | 0 | 1 | 2 |", "",
        "门禁细节与 CI 接入见 `ci-gates.md`。", "",
    ]
    return "\n".join(lines) + "\n"


