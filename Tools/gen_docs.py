def parse_schema() -> str:
    sql_src = (ROOT / "Server/schema/init.sql").read_text(encoding="utf-8")
    rebuild = (ROOT / "Server/schema/rebuild_fts.sql").read_text(encoding="utf-8")
    lines = [
        "# DuckDB 存储参考",
        BANNER,
        "",
        "> 生成来源：`Server/schema/init.sql`、`Server/schema/rebuild_fts.sql`。"
        "字段契约以 `docs/reference/protocol.md` 为准；本页是 DDL 的结构化投影。",
        "",
        "## schema_meta",
        "",
    ]
    meta = re.findall(r"INSERT OR REPLACE INTO schema_meta VALUES \('([^']+)', '([^']+)'\)", sql_src)
    lines += [_table(["key", "value"], [[k, v] for k, v in meta]), ""]

    for match in re.finditer(r"CREATE TABLE IF NOT EXISTS (\w+)\s*\((.*?)\n\);", sql_src, re.S):
        name, body = match.group(1), match.group(2)
        if name == "schema_meta":  # already rendered above from the INSERT values
            continue
        rows: list[list[Any]] = []
        for raw in body.splitlines():
            code, _, comment = raw.strip().partition("--")
            code = code.strip().rstrip(",")
            if not code:
                continue
            parts = code.split(None, 1)
            if len(parts) < 2:
                continue
            col, typ = parts[0].strip(), parts[1].strip()
            if col.upper() in {"PRIMARY", "UNIQUE", "CHECK", "CONSTRAINT", "FOREIGN"}:
                continue
            rows.append([f"`{col}`", f"`{typ}`", comment.strip()])
        lines += [f"## {name}", "", _table(["列", "类型", "说明"], rows), ""]

    view = re.search(r"CREATE OR REPLACE VIEW v_search AS.*?;", sql_src, re.S)
    if view:
        lines += [
            "## v_search 投影视图",
            "",
            "把 `domain_spec` 中的键投影为可过滤列，避免在物理表中新增列。",
            "",
            _fence("sql", view.group(0)),
            "",
        ]

    pragmas = [ln.strip() for ln in sql_src.splitlines()
               if ln.strip().startswith("PRAGMA") and "fts_index" in ln]
    lines += [
        "## FTS 索引（快照语义）",
        "",
        "DuckDB 的 FTS 索引**不会随 INSERT 自动更新**，每次批量灌库后必须重建：",
        "",
        _fence("sql", "\n".join(
            [ln.strip() for ln in rebuild.splitlines()
             if ln.strip().startswith("PRAGMA")])),
        "",
        "初始化时执行的建索引语句：",
        "",
        _fence("sql", "\n".join(pragmas)),
        "",
        "## 查重查询",
        "",
        "`ual-cli lint-duplicates` 使用 `db.duplicate_pairs()` 的余弦自连接，核心表达式为",
        "`array_cosine_similarity(a.fingerprint_vec, b.fingerprint_vec)`，"
        "并要求 DuckDB >= 1.1（已在 2.0.0 实测）。完整 SQL 见 `Server/ual_common/db.py`。",
        "",
    ]
    return "\n".join(lines) + "\n"


